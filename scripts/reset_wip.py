"""Reset WIP.md's generated state block after merging a feature branch to main, and guard its line endings.

WIP.md is the gitignored, Syncthing-synced cross-machine handoff file (`AGENTS.md` Part 1
section 3). Two things follow from "gitignored" that make this script carry more than a
couple of substitutions.

WHY A MARKED BLOCK, AND NOT THE OLD TWO SUBSTITUTIONS. This script owns exactly ONE block of
WIP.md: the lines between the two marker comments below, which it regenerates from git and
Cargo.toml on every `just merge-pr`. Everything outside the markers is left byte-for-byte
alone.

    <!-- BEGIN merge-pr state ... -->
    ...generated table: active branch, main HEAD, version, newest tag, date...
    <!-- END merge-pr state -->

If the markers are absent the block is inserted once, at the top of the file. If they are
duplicated, unpaired or out of order the script refuses and changes nothing: guessing which
copy is "the real one" is the exact failure this design replaces.

The previous version rewrote lines matching `^### Active Branch:` and
`^\\*\\*Latest commit on main\\*\\*:`. That left any branch-specific lines around them (such as
`**Latest commit on branch**:` or `**Version**: 0.x.y on this branch`) stale after a merge,
and in the sibling repo `retch` (#259) matched stale headings hundreds of lines down the file
or prose quoting the headers verbatim. A block the script owns outright cannot drift from the
thing it describes, cannot be confused with prose, and cannot leave half-updated state lines
behind.

WHY THE LINE-ENDING GUARD LIVES HERE. `.gitattributes` pins `* text=auto eol=lf` for the
whole tree, and `scripts/text_check.py` refuses a carriage return in tracked text -- but
BOTH work through git, and `git ls-files` never offers a gitignored path. WIP.md is
therefore the one text file in this repository with no automatic protection, and it is
rewritten on every `just merge-pr` by this script. LF is the base model for every non-binary
file here, so the file wants the same guarantee the rest of the tree gets. `--check-endings`
supplies it, and `just check` runs it via `just wip-check`.

WHY THE REWRITE PRESERVES THE TERMINATOR RATHER THAN HARDCODING LF. Reading with
`read_text()` and writing with `write_text()` silently translates: a CRLF file read on Linux
comes back with `\\n` and goes out as LF. That converts a file as a SIDE EFFECT OF A MERGE,
which is a thing to be caught, not a thing to do quietly -- the sibling repo `retch` shipped
exactly that accident in its v0.17.12, in the other direction. So this script reads and
writes BYTES, re-applying whatever terminator it found, and the decision that the terminator
should be LF is asserted by `--check-endings` where it is visible, rather than falling out of
an I/O default where it is not.
"""

import argparse
import datetime
import re
import subprocess
import sys
from pathlib import Path

TEMPLATE_VERSION = 2

BEGIN_MARKER = (
    "<!-- BEGIN merge-pr state: generated by scripts/reset_wip.py on every `just merge-pr`."
    " Anything between these markers is overwritten; write notes outside them. -->"
)
END_MARKER = "<!-- END merge-pr state -->"

# Whole-line matches only. A marker mentioned mid-sentence is prose, not a marker; one that
# starts a line is treated as a marker even inside a code fence, and then the duplicate
# check refuses rather than guessing.
_BEGIN_RE = re.compile(r"^<!-- BEGIN merge-pr state\b.*-->[ \t]*$", re.MULTILINE)
_END_RE = re.compile(r"^" + re.escape(END_MARKER) + r"[ \t]*$", re.MULTILINE)


def read_preserving_newlines(path):
    """Return (text_with_lf_endings, dominant_terminator).

    Read as BYTES rather than text: `read_text()` applies universal newlines, which is
    exactly the conversion this function exists to avoid. The terminator is chosen by
    majority so a file with a few stray lone LFs in an otherwise CRLF document still
    round-trips as CRLF.
    """
    raw = path.read_bytes()
    crlf = raw.count(b"\r\n")
    lf = raw.count(b"\n") - crlf
    newline = "\r\n" if crlf > lf else "\n"
    return raw.decode("utf-8").replace("\r\n", "\n"), newline


def write_preserving_newlines(path, text, newline):
    """Write BYTES, re-applying `newline`. Never `write_text`, which re-translates."""
    path.write_bytes(text.replace("\n", newline).encode("utf-8"))


def classify_endings(raw):
    """Return (ok, detail) for a WIP.md's raw bytes. Pure, so the self-test can pin it.

    `WIP.md` is gitignored, so `.gitattributes` never applies to it and
    `scripts/text_check.py` -- which walks `git ls-files` -- cannot see it. It is therefore
    the one text file in the tree with no automatic protection, and it is expected to be LF.
    This is what supplies the missing guard.

    A file with NO newline at all passes: an empty or single-line WIP.md carries no
    evidence either way, and a guard that fires on no evidence is a guard that gets
    deleted. Only an actual carriage return is a failure.
    """
    crlf = raw.count(b"\r\n")
    lone_cr = raw.count(b"\r") - crlf
    lf = raw.count(b"\n") - crlf
    if not crlf and not lone_cr:
        return True, f"LF ({lf} lines)" if lf else "no newlines (nothing to check)"
    return False, f"{crlf} CRLF pair(s), {lone_cr} lone CR, {lf} lone LF"


def check_endings(wip_file):
    """Fail if WIP.md holds any carriage return. An absent file passes.

    Absent is not a failure: WIP.md is per-machine and untracked, so a fresh clone and CI
    both legitimately have none. Counting BYTES rather than reaching for `grep -c` is
    deliberate -- see `~/AGENTS.md` section 17, where that idiom returns the file's line
    count wearing a carriage-return costume.
    """
    if not wip_file.exists():
        print("WIP.md absent (per-machine, untracked) -- nothing to check")
        return 0
    ok, detail = classify_endings(wip_file.read_bytes())
    if ok:
        print(f"WIP.md is {detail}")
        return 0
    print(
        f"WIP.md contains carriage returns ({detail}); this tree is LF.\n"
        f"  It is gitignored, so .gitattributes and text-check cannot reach it.\n"
        f"  Repair in place -- NEVER via a temp file in /tmp, which would carry\n"
        f"  user_tmp_t into this Syncthing folder (~/AGENTS.md sec.12):\n"
        f"  python3 -c \"import pathlib;p=pathlib.Path('WIP.md');"
        f"p.write_bytes(p.read_bytes().replace(b'\\r\\n',b'\\n').replace(b'\\r',b''))\"",
        file=sys.stderr,
    )
    return 1


def run(cmd, required=True):
    """Run `cmd` and return its stripped stdout.

    `required=False` returns None on failure instead of exiting -- for facts that may
    legitimately be absent, such as a tag in a repository that has never been released.
    """
    try:
        # encoding="utf-8" (not the platform default) so commit subjects with
        # non-Latin-1 characters -- e.g. "→" or an em-dash -- decode correctly
        # on Windows (cp1252) too.
        return subprocess.run(
            cmd, capture_output=True, text=True, encoding="utf-8", check=True
        ).stdout.strip()
    except subprocess.CalledProcessError as e:
        if not required:
            return None
        print(f"Command failed: {' '.join(cmd)}", file=sys.stderr)
        if e.stdout:
            print(e.stdout, file=sys.stderr)
        if e.stderr:
            print(e.stderr, file=sys.stderr)
        sys.exit(e.returncode)


def read_cargo_version(cargo_file):
    """Return the package version from Cargo.toml, or None if unreadable."""
    try:
        for line in cargo_file.read_text(encoding="utf-8").splitlines():
            m = re.match(r'version\s*=\s*"([^"]+)"', line)
            if m:
                return m.group(1)
    except OSError:
        pass
    return None


def _cell(value):
    """Make `value` safe inside a Markdown table cell.

    A `|` in a commit subject would otherwise end the cell and shift every column after it,
    and a newline would end the row.
    """
    return value.replace("|", "\\|").replace("\n", " ")


def render_state_block(state):
    """Render the generated block, markers included, with LF line endings.

    `state` keys: branch, head_hash, head_subject, version, newest_tag, date. Missing
    values render as `unknown`/`none` rather than raising, so a partially readable
    repository still produces a truthful block instead of no block. Pure: no I/O, so the
    self-test can pin the output exactly.
    """
    branch = state.get("branch")
    if branch in (None, "main"):
        active = "none — `main` is current"
    else:
        # merge-pr checks out main before calling this, so anything else is worth seeing.
        active = f"`{_cell(branch)}` — **not `main`**; check what is checked out"

    version = f"`etr` {_cell(state.get('version') or 'unknown')}"

    head = f"`{_cell(state.get('head_hash') or 'unknown')}`"
    if state.get("head_subject"):
        head += f" — {_cell(state['head_subject'])}"

    tag = state.get("newest_tag")
    rows = [
        ("Active branch", active),
        ("main HEAD", head),
        ("Version", version),
        ("Newest tag", f"`{_cell(tag)}`" if tag else "none"),
        ("Updated", f"{_cell(state.get('date') or 'unknown')}, by `just merge-pr`"),
    ]
    lines = [
        BEGIN_MARKER,
        "## Repository state (generated)",
        "",
        "| | |",
        "|---|---|",
        *[f"| **{label}** | {value} |" for label, value in rows],
        "",
        END_MARKER,
    ]
    return "\n".join(lines) + "\n"


def apply_state_block(text, block):
    """Return (new_text, action) with `block` placed in `text`.

    `text` must already be LF-normalised. action is "replaced" or "inserted". Raises
    ValueError, and changes nothing, when the markers are duplicated, unpaired or out of
    order -- the caller decides what to do; this function never guesses.
    """
    begins = list(_BEGIN_RE.finditer(text))
    ends = list(_END_RE.finditer(text))

    if not begins and not ends:
        # First run on this WIP.md: put the block at the very top, where a reader starts.
        return block + "\n" + text, "inserted"
    if len(begins) != 1 or len(ends) != 1:
        raise ValueError(
            f"expected exactly one BEGIN and one END merge-pr state marker, found "
            f"{len(begins)} BEGIN and {len(ends)} END"
        )
    begin, end = begins[0], ends[0]
    if end.start() < begin.end():
        raise ValueError("the END merge-pr state marker comes before the BEGIN marker")

    # Consume the END marker's own newline, so the block's trailing newline replaces it
    # rather than doubling it.
    stop = end.end() + 1 if text[end.end():end.end() + 1] == "\n" else end.end()
    return text[:begin.start()] + block + text[stop:], "replaced"


def update_file(path, state):
    """Read `path`, place the rendered block, write it back. Returns the action taken."""
    text, newline = read_preserving_newlines(path)
    new_text, action = apply_state_block(text, render_state_block(state))
    write_preserving_newlines(path, new_text, newline)
    return action


def gather_state(root_dir):
    """Read the facts the block reports from git and Cargo.toml."""
    return {
        "branch": run(["git", "rev-parse", "--abbrev-ref", "HEAD"]),
        "head_hash": run(["git", "rev-parse", "--short", "HEAD"]),
        "head_subject": run(["git", "log", "-1", "--format=%s"]),
        "version": read_cargo_version(root_dir / "Cargo.toml"),
        # No tag yet is a legitimate state, not an error.
        "newest_tag": run(["git", "describe", "--tags", "--abbrev=0"], required=False),
        "date": datetime.date.today().isoformat(),
    }


def self_test():
    """Assert the block behaviour and the line-ending round trip, in both directions.

    Several cases pin ways this could be WRONG rather than the way it is right: prose that
    quotes the old header strings must survive, malformed markers must refuse rather than
    guess, and a rewrite must not touch a single byte outside the markers.
    """
    import contextlib
    import io
    import tempfile

    failures = []

    def quietly(fn, *a):
        """Run a guard with its output captured -- a control firing is not a failure here,
        and printing its refusal makes a passing self-test read like a failing one."""
        with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
            return fn(*a)

    def check(name, cond, detail=""):
        if not cond:
            failures.append(f"{name}: {detail}")

    state = {
        "branch": "main",
        "head_hash": "abc1234",
        "head_subject": "Fix a | b (#1)",
        "version": "0.10.14",
        "newest_tag": "v0.10.6",
        "date": "2026-11-01",
    }
    block = render_state_block(state)

    # --- rendering ---------------------------------------------------------------------
    check("block starts with BEGIN", block.startswith(BEGIN_MARKER + "\n"), repr(block[:40]))
    check("block ends with END", block.endswith(END_MARKER + "\n"), repr(block[-40:]))
    check("pipe in subject is escaped", "Fix a \\| b (#1)" in block, block)
    check("main renders as none", "none — `main` is current" in block, block)
    check("version rendered", "`etr` 0.10.14" in block, block)
    off_main = render_state_block({**state, "branch": "feature/x"})
    check("off-main branch is flagged", "**not `main`**" in off_main, off_main)
    no_tag = render_state_block({**state, "newest_tag": None})
    check("no tag renders as none", "| **Newest tag** | none |" in no_tag, no_tag)
    check(
        "the block never contains the old header strings",
        "### Active Branch:" not in block and "**Latest commit on main**:" not in block,
        block,
    )

    # --- placement ---------------------------------------------------------------------
    # Prose quoting the old header strings must remain untouched.
    prose = (
        "## Old entry\n### Active Branch: feature/old\n"
        "**Latest commit on main**: `0000000` - ancient\nnotes\n"
    )
    inserted, action = apply_state_block(prose, block)
    check("absent markers -> inserted", action == "inserted", action)
    check("inserted at the very top", inserted.startswith(BEGIN_MARKER), inserted[:60])
    check("prose after an insert is byte-identical", inserted.endswith("\n" + prose), repr(inserted[-80:]))

    newer = render_state_block({**state, "head_hash": "def5678", "head_subject": "Next"})
    replaced, action = apply_state_block(inserted, newer)
    check("present markers -> replaced", action == "replaced", action)
    check("replacement took effect", "`def5678`" in replaced and "`abc1234`" not in replaced, replaced)
    check("prose after a replace is byte-identical", replaced.endswith("\n" + prose), repr(replaced[-80:]))
    again, _ = apply_state_block(replaced, newer)
    check("replacing is idempotent", again == replaced, "a second run changed the file")

    middle = "# WIP\nintro\n" + block + "tail\n"
    moved, _ = apply_state_block(middle, newer)
    check(
        "a block mid-file is replaced where it is",
        moved.startswith("# WIP\nintro\n" + BEGIN_MARKER) and moved.endswith(END_MARKER + "\ntail\n"),
        repr(moved),
    )

    mention = "Prose may mention " + END_MARKER + " mid-line.\n"
    kept, action = apply_state_block(mention, block)
    check("a mid-line mention is not a marker", action == "inserted" and kept.endswith(mention), action)

    for name, bad in [
        ("duplicate block", block + "x\n" + block),
        ("BEGIN without END", BEGIN_MARKER + "\nstuff\n"),
        ("END without BEGIN", "stuff\n" + END_MARKER + "\n"),
        ("END before BEGIN", END_MARKER + "\n" + BEGIN_MARKER + "\n"),
    ]:
        try:
            apply_state_block(bad, block)
            check(f"{name} refuses", False, "no ValueError raised")
        except ValueError:
            pass

    # --- line endings, end to end through update_file() --------------------------------
    with tempfile.TemporaryDirectory() as d:
        tmp = Path(d)

        # 1. CRLF in, CRLF out -- conversion must never be a merge side effect.
        f = tmp / "crlf.md"
        f.write_bytes(b"### Active Branch: feature/x\r\nbody\r\n**Latest commit on main**: `old`\r\n")
        check("CRLF first run inserts", update_file(f, state) == "inserted")
        check("CRLF second run replaces", update_file(f, state) == "replaced")
        raw = f.read_bytes()
        lone_lf = raw.count(b"\n") - raw.count(b"\r\n")
        check(
            "CRLF survives, with no lone LF",
            lone_lf == 0 and raw.count(b"\r\n") > 3,
            f"crlf={raw.count(bytes([13, 10]))} lone_lf={lone_lf}",
        )
        check(
            "old header lines untouched in the file",
            b"### Active Branch: feature/x\r\n" in raw and b"**Latest commit on main**: `old`\r\n" in raw,
            repr(raw[-80:]),
        )
        check("check-endings refuses CRLF", quietly(check_endings, f) == 1, "CRLF file passed")

        # 2. LF in, LF out.
        f2 = tmp / "lf.md"
        f2.write_bytes(b"notes\n")
        update_file(f2, state)
        check("LF round-trips", b"\r" not in f2.read_bytes(), "a CR was introduced")
        check("check-endings accepts LF", quietly(check_endings, f2) == 0, "LF file refused")

        # 3. A real WIP.md-shaped LF file survives a full insert+replace cycle with no CR.
        f4 = tmp / "converted.md"
        f4.write_bytes(b"# WIP\n" + b"a line\n" * 50)
        update_file(f4, state)
        update_file(f4, state)
        raw4 = f4.read_bytes()
        check(
            "a converted WIP.md stays LF across two merges",
            b"\r" not in raw4,
            f"CR reappeared: {raw4.count(bytes([13]))}",
        )
        check("classify_endings passes the converted file", classify_endings(raw4)[0], classify_endings(raw4)[1])

        # 4. check_endings on an absent file is a PASS.
        check(
            "absent WIP.md passes",
            quietly(check_endings, tmp / "definitely-absent.md") == 0,
            "a missing file was treated as a failure",
        )

        # 5. A refusal writes nothing.
        f3 = tmp / "bad.md"
        before = (block + block).encode("utf-8")
        f3.write_bytes(before)
        try:
            update_file(f3, state)
            check("malformed file refuses", False, "no ValueError raised")
        except ValueError:
            check("a refusal leaves the file untouched", f3.read_bytes() == before, "file changed")

    # --- classify_endings, the guard behind `just wip-check` ---------------------------
    check(
        "LF verdict",
        classify_endings(b"a\nb\n") == (True, "LF (2 lines)"),
        str(classify_endings(b"a\nb\n")),
    )
    check("CRLF is refused", not classify_endings(b"a\r\nb\r\n")[0], "a CRLF file passed")
    check("a lone CR is refused", not classify_endings(b"a\rb\n")[0], "a lone CR passed")
    check(
        "one stray CRLF in an LF file is still refused",
        not classify_endings(b"a\n" * 99 + b"b\r\n")[0],
        "a majority-LF file with one CRLF passed -- drift starts as one line",
    )
    check(
        "no newlines passes",
        classify_endings(b"")[0] and classify_endings(b"x")[0],
        "an empty or single-line file was flagged",
    )

    if failures:
        for line in failures:
            print(f"FAIL: {line}", file=sys.stderr)
        return 1
    print(f"reset_wip.py self-test passed (template v{TEMPLATE_VERSION})")
    return 0


def main():
    # WIP.md and commit subjects contain non-Latin-1 characters (em-dashes, "→").
    # Force UTF-8 on stdout so the final status print does not crash under a cp1252
    # console on Windows (where `just merge-pr` runs it).
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except (AttributeError, ValueError):
        pass

    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--self-test", action="store_true", help="run the guard's own negative controls")
    parser.add_argument("--check-endings", action="store_true", help="fail if WIP.md holds a carriage return")
    args = parser.parse_args()

    root_dir = Path(__file__).resolve().parent.parent
    wip_file = root_dir / "WIP.md"

    if args.self_test:
        sys.exit(self_test())
    if args.check_endings:
        sys.exit(check_endings(wip_file))

    if not wip_file.exists():
        print("WIP.md not found. Skipping reset.", file=sys.stderr)
        return

    state = gather_state(root_dir)
    try:
        action = update_file(wip_file, state)
    except ValueError as e:
        print(
            f"reset_wip.py: WIP.md NOT updated: {e}. Fix the markers by hand; nothing was written.",
            file=sys.stderr,
        )
        sys.exit(1)

    where = "at the top of the file (first run)" if action == "inserted" else "in place"
    print(
        f"WIP.md state block {action} {where}: main HEAD `{state['head_hash']}`, "
        f"v{state['version']}. Hand-written entries outside the markers are unchanged."
    )


if __name__ == "__main__":
    main()
